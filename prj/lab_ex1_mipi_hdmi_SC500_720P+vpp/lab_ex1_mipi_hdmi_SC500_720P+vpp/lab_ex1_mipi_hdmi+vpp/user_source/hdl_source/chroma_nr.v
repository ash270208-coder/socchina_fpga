`timescale 1ns / 1ps
//=============================================================================
// chroma_nr.v -- 色度降噪 (chroma noise reduction, luma preserving)
//
// 【原理】
//   1) 把相邻 4 个像素的 R/G/B 各自取平均   -> 颜色(色度)被平滑, 彩色噪点变小;
//   2) 再把"当前像素比平均值多出来的那部分亮度"加回去 -> 亮度完全不变、依旧锐利。
//   数学上: 输出亮度 Y' = Y (逐像素严格相等), 而 R-G / R-B 等色差取自平均值,
//           等价于  R' = R_avg + (Y - Y_avg)/4 , 这里 Y 用未归一化亮度 Y = R+2G+B。
//
// 【为什么对你们这个工程特别有效】
//   AWB 把 R 乘 1.75、B 乘 2.75, 彩噪被放大得很厉害; 本模块只动色度、不动亮度,
//   所以画面不会变糊, 也不改变亮度观感 —— 是副作用最小的降噪手段。
//
// 【时序】
//   内部 3 拍 (p0/p1/p2/p3 移位链, 亮度取中心抽头 p2, 与输出同拍)。
//   在 vpp_top 里从 raw_rgb_d[12] (第 13 拍) 抽输入: 13 + 3 = 16 拍,
//   正好落在所有显示档要求的第 16 拍, 不需要改任何控制信号或延迟链。
//
// 【只做了水平方向】
//   只用同一行的 4 个像素, 不占行缓存/BRAM: 水平方向彩噪约 -6dB, 垂直方向不降。
//   若以后还想更强, 加 1 个行缓存做 2x2 / 3x3 即可。
//=============================================================================
module chroma_nr (
    input  wire        I_clk,
    input  wire        I_rst_n,
    input  wire [23:0] I_rgb,     // 输入 RGB888
    output wire [23:0] O_rgb      // 色度降噪后的 RGB888 (亮度不变)
);

    //-------------------------------------------------------------------------
    // 1. 4 级移位链: p0 最新 ... p3 最旧; 中心抽头 p2 的像素与输出同拍
    //-------------------------------------------------------------------------
    reg [23:0] p0, p1, p2, p3;

    always @(posedge I_clk or negedge I_rst_n) begin
        if (!I_rst_n) begin
            p0 <= 24'd0;
            p1 <= 24'd0;
            p2 <= 24'd0;
            p3 <= 24'd0;
        end
        else begin
            p0 <= I_rgb;
            p1 <= p0;
            p2 <= p1;
            p3 <= p2;
        end
    end

    //-------------------------------------------------------------------------
    // 2. 4 抽头平均 (÷4 就是 >>2, 不需要除法器)
    //    注意位宽: 4 个 8bit 相加最大 1020, 所以每个操作数先扩到 10 位
    //-------------------------------------------------------------------------
    wire [9:0] r_sum = {2'b00, p0[23:16]} + {2'b00, p1[23:16]}
                     + {2'b00, p2[23:16]} + {2'b00, p3[23:16]};
    wire [9:0] g_sum = {2'b00, p0[15: 8]} + {2'b00, p1[15: 8]}
                     + {2'b00, p2[15: 8]} + {2'b00, p3[15: 8]};
    wire [9:0] b_sum = {2'b00, p0[ 7: 0]} + {2'b00, p1[ 7: 0]}
                     + {2'b00, p2[ 7: 0]} + {2'b00, p3[ 7: 0]};

    wire [7:0] r_avg = r_sum[9:2];
    wire [7:0] g_avg = g_sum[9:2];
    wire [7:0] b_avg = b_sum[9:2];

    //-------------------------------------------------------------------------
    // 3. 亮度差: (中心像素亮度 - 平均亮度) / 4
    //    未归一化亮度 Y = R + 2G + B (最大 1020, 用 10 位)
    //    全书用"无符号 + 偏置"算法, 避免有符号数语法在综合器上的兼容问题:
    //      dy_p = (Y_cur - Y_avg + 1020) >> 2  ∈ [0,510]
    //      它等价于有符号值 (dy_p - 255), 范围 -255..255
    //-------------------------------------------------------------------------
    wire [9:0] y_cur = {2'b00, p2[23:16]} + {1'b0, p2[15:8], 1'b0} + {2'b00, p2[7:0]};
    wire [9:0] y_avg = {2'b00, r_avg}     + {1'b0, g_avg,     1'b0} + {2'b00, b_avg};

    wire [10:0] dy_u = {1'b0, y_cur} + 11'd1020 - {1'b0, y_avg};   // 0 .. 2040 (11bit)
    wire [9:0]  dy_p = {1'b0, dy_u[10:2]};                         // dy_u >> 2, 0 .. 510
                                                                   // 注意: 位选只能取到第 10 位,
                                                                   // 取到第 11 位就越界(仿真会变 x)

    //-------------------------------------------------------------------------
    // 4. 加回亮度细节: out = avg + (dy_p - 255) = (avg + dy_p) - 255, 再饱和
    //-------------------------------------------------------------------------
    wire [10:0] r_tmp = {3'b000, r_avg} + {1'b0, dy_p};   // 0 .. 765
    wire [10:0] g_tmp = {3'b000, g_avg} + {1'b0, dy_p};
    wire [10:0] b_tmp = {3'b000, b_avg} + {1'b0, dy_p};

    wire [10:0] r_sub = r_tmp - 11'd255;
    wire [10:0] g_sub = g_tmp - 11'd255;
    wire [10:0] b_sub = b_tmp - 11'd255;

    assign O_rgb[23:16] = (r_tmp < 11'd255) ? 8'd0   :
                          (r_tmp > 11'd510) ? 8'd255 : r_sub[7:0];
    assign O_rgb[15: 8] = (g_tmp < 11'd255) ? 8'd0   :
                          (g_tmp > 11'd510) ? 8'd255 : g_sub[7:0];
    assign O_rgb[ 7: 0] = (b_tmp < 11'd255) ? 8'd0   :
                          (b_tmp > 11'd510) ? 8'd255 : b_sub[7:0];

endmodule
